"""Read structured athlete_profile fields from Supabase."""
from __future__ import annotations

import logging

from .athlete_memory import get_athlete_memory
from .client import get_supabase, row, rows

logger = logging.getLogger(__name__)


def get_meal_variety_preference(user_id: str) -> str:
    """Return the athlete's meal variety preference ('minimal'/'balanced'/'high'), defaulting to 'balanced'."""
    try:
        sb = get_supabase()
        result = row(
            sb.table("athlete_profile")
            .select("meal_variety_preference")
            .eq("user_id", user_id)
            .maybe_single()
            .execute()
        )
        value = (result or {}).get("meal_variety_preference")
        return value or "balanced"
    except Exception as exc:
        logger.warning("Failed to load meal variety preference for %s: %s", user_id, exc)
        return "balanced"


def get_meal_location_context(user_id: str) -> str:
    """Return a one-line summary of the athlete's country + grocery store access, for biasing
    meal-recommendation ingredients toward what's actually available to them. Empty string if
    neither field is set.
    """
    try:
        sb = get_supabase()
        data = row(
            sb.table("athlete_profile")
            .select("country,grocery_stores_notes")
            .eq("user_id", user_id)
            .maybe_single()
            .execute()
        ) or {}
        country = (data.get("country") or "").strip()
        stores = (data.get("grocery_stores_notes") or "").strip()
        parts = []
        if country:
            parts.append(f"Country: {country}")
        if stores:
            parts.append(f"Store access: {stores}")
        return " | ".join(parts)
    except Exception as exc:
        logger.warning("Failed to load meal location context for %s: %s", user_id, exc)
        return ""


