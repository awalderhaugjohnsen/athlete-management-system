def get_athlete_language(user_id: str) -> str:
    """Return the athlete's selected language ('en'/'no') from user_settings, defaulting to 'en'.

    Read by the coaching pipeline so LangGraph prompts can instruct the LLM to write
    athlete-facing text (plan rationale, feedback, reports) in the same language the web UI
    is showing — see supabase/migrations/042_user_settings_language.sql.
    """
    try:
        sb = get_supabase()
        result = row(
            sb.table("user_settings")
            .select("language")
            .eq("user_id", user_id)
            .maybe_single()
            .execute()
        )
        value = (result or {}).get("language")
        return value if value in ("en", "no") else "en"
    except Exception as exc:
        logger.warning("Failed to load language setting for %s: %s", user_id, exc)
        return "en"


